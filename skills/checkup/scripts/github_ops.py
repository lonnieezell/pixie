"""GitHub side of the pipeline: file findings as issues or advisories, promote for auto-fix.

Every call goes through `run(args, input=None) -> (code, stdout, stderr)` so tests can
swap in a fake `gh`. GitHub is the memory: dedupe is a search for the fingerprint
tokens written into each issue, so no local state is needed between runs.
"""
import json
import re
import subprocess
from datetime import datetime, timedelta
from pathlib import Path

import findings as F

NOTICE = "> *This comment was generated by AI (pixie {source}).*\n\n"
STILL_PRESENT = "pixie-still-present"
PROMOTED = "pixie-autofix-promoted"
AGENT_ROLES = ("ready-for-agent", "agent-working", "agent-pr", "agent-blocked")


class GhError(RuntimeError):
    pass


def subprocess_run(args, input=None):
    p = subprocess.run(args, input=input, capture_output=True, text=True)
    return p.returncode, p.stdout, p.stderr


def gh(run, *args, input=None):
    code, out, err = run(["gh", *args], input=input)
    if code != 0:
        raise GhError(f"gh {' '.join(args[:3])} failed: {err.strip()}")
    return out


def gh_json(run, *args):
    return json.loads(gh(run, *args) or "null")


# --- labels --------------------------------------------------------------------------

_ROW = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|")


def label_map(repo_root="."):
    """Role -> label from docs/agents/pixie-labels.md. Missing roles map to themselves."""
    path = Path(repo_root) / "docs/agents/pixie-labels.md"
    if not path.exists():
        return {}
    return {m.group(1): m.group(2) for m in map(_ROW.match, path.read_text().splitlines()) if m}


def labels_for(f, source, roles):
    out = [roles.get("needs-triage", "needs-triage"), "bug", source, f"severity:{f['severity']}"]
    if f["dimension"] != "bug":
        out.append(f["dimension"])
    return out


def ensure_labels(run, wanted):
    have = {l["name"] for l in gh_json(run, "label", "list", "--json", "name", "--limit", "500")}
    for name in sorted(set(wanted) - have):
        gh(run, "label", "create", name)


# --- filing --------------------------------------------------------------------------

def security_mode(mode, visibility):
    if mode != "auto":
        return mode
    return "issues" if visibility in ("PRIVATE", "INTERNAL") else "advisory"


def find_existing(run, toks):
    """The issue carrying any of these tokens, open ones first.

    GitHub search allows five OR operators and tokenizes on hyphens, so tokens go in
    batches of six and every hit is re-checked against its body.
    """
    hits = []
    for i in range(0, len(toks), 6):
        batch = toks[i : i + 6]
        query = " OR ".join(f'"{t}"' for t in batch) + " in:body"
        found = gh_json(run, "issue", "list", "--state", "all", "--search", query,
                        "--json", "number,state,stateReason,url,labels,body", "--limit", "10") or []
        hits += [h for h in found if any(t in (h.get("body") or "") for t in batch)]
    hits.sort(key=lambda h: (h["state"] != "OPEN", -h["number"]))
    return hits[0] if hits else None


def _recent(comments, marker, now, days):
    cutoff = now - timedelta(days=days)
    for c in comments or []:
        if marker in c.get("body", "") and _parse(c["createdAt"]) >= cutoff:
            return True
    return False


def _parse(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00"))


def _still_present(run, issue, f, source, now):
    comments = gh_json(run, "issue", "view", str(issue["number"]), "--json", "comments")["comments"]
    if _recent(comments, STILL_PRESENT, now, 7):
        return "unchanged"
    body = NOTICE.format(source=source) + f"Still present on {now.date()} (severity {f['severity']})."
    for ext in f.get("externals", []):
        body += (f" `{F.inline(ext['tracker'], 40)}`: {F.shown(ext.get('events'))} events, "
                 f"{F.shown(ext.get('users'))} users in the latest window.")
    gh(run, "issue", "comment", str(issue["number"]), "--body", body + f"\n\n<!-- {STILL_PRESENT} -->")
    return "commented"


def _create(run, f, labels, body):
    args = ["issue", "create", "--title", F.issue_title(f), "--body-file", "-"]
    for l in labels:
        args += ["--label", l]
    url = gh(run, *args, input=body).strip().splitlines()[-1]
    return int(url.rstrip("/").rsplit("/", 1)[-1]), url


ADVISORY_STATES = ("triage", "draft", "published", "closed")


def list_advisories(run):
    """Every repository advisory, all states and pages. The docs don't promise that
    leaving out `state` returns all of them, so each state is listed on its own."""
    out = []
    for state in ADVISORY_STATES:
        text = gh(run, "api", "--paginate", f"repos/{{owner}}/{{repo}}/security-advisories?state={state}&per_page=100",
                  "--jq", ".[] | {state, html_url, description}")
        out += [json.loads(line) for line in text.splitlines() if line.strip()]
    return out


def _existing_advisory(advisories, f):
    """Open (triage or draft) first, then closed, then published."""
    hits = [a for a in advisories if any(t in (a.get("description") or "") for t in F.tokens(f))]
    rank = {"triage": 0, "draft": 0, "closed": 1, "published": 2}
    return min(hits, key=lambda a: rank.get(a.get("state"), 3)) if hits else None


def _create_advisory(run, f, body, repo_name):
    payload = {
        "summary": F.issue_title(f),
        "description": body,
        "severity": f["severity"],
        "vulnerabilities": [{"package": {"ecosystem": "other", "name": repo_name}}],
    }
    adv = json.loads(gh(run, "api", "-X", "POST", "repos/{owner}/{repo}/security-advisories",
                        "--input", "-", input=json.dumps(payload)))
    return adv.get("html_url")


def fileable(f, config):
    return (f["severity"] in config["fileSeverities"] and f.get("evidence_rung", 0) >= 3
            and not f.get("possibly_fixed") and not f.get("stale"))


def file_all(run, confirmed, config, *, source, sha, repo, roles, now):
    """File every eligible finding. Returns one result dict per finding considered.

    repo: {"nameWithOwner", "visibility"} from `gh repo view`. A GitHub failure on one
    finding is recorded as `error` and the rest are still filed.
    """
    todo = [f for f in confirmed if fileable(f, config)]
    mode = security_mode(config["securityFindings"], repo["visibility"])
    if todo:
        ensure_labels(run, {l for f in todo for l in labels_for(f, source, roles)})
    advisories = None
    results, created = [], 0
    for f in todo:
        res = {"id": f["id"], "severity": f["severity"], "dimension": f["dimension"]}
        results.append(res)
        try:
            body = F.render_brief(f, sha, source)
            if f["dimension"] == "security" and mode == "report-only":
                res["action"] = "report-only"
                continue
            if f["dimension"] == "security" and mode == "advisory":
                if advisories is None:
                    advisories = list_advisories(run)
                adv = _existing_advisory(advisories, f)
                if adv and adv["state"] in ("triage", "draft"):
                    res.update(action="advisory-exists", url=adv["html_url"])
                elif adv and adv["state"] == "closed":
                    res.update(action="suppressed", url=adv["html_url"])
                elif created >= config["maxIssuesPerRun"]:
                    res["action"] = "skipped-cap"
                else:
                    if adv:
                        body = f"Regression of {adv['html_url']}, which was published as fixed.\n\n" + body
                    url = _create_advisory(run, f, body, repo["nameWithOwner"].split("/")[-1])
                    created += 1
                    res.update(action="advisory-regression" if adv else "advisory-created", url=url)
                continue
            existing = find_existing(run, F.tokens(f))
            if existing and existing["state"] == "OPEN":
                res.update(action=_still_present(run, existing, f, source, now),
                           issue=existing["number"], url=existing["url"],
                           labels=[l["name"] for l in existing.get("labels", [])])
                continue
            if existing and existing.get("stateReason") in ("NOT_PLANNED", "DUPLICATE"):
                res.update(action="suppressed", issue=existing["number"])
                continue
            if created >= config["maxIssuesPerRun"]:
                res["action"] = "skipped-cap"
                continue
            labels = labels_for(f, source, roles)
            if existing:
                body = f"Regression of #{existing['number']}, which was closed as fixed.\n\n" + body
            number, url = _create(run, f, labels, body)
            created += 1
            res.update(action="regression" if existing else "created", issue=number, url=url, labels=labels)
        except GhError as e:
            if f["dimension"] == "security" and mode == "advisory":
                res.update(action="advisory-failed", error=str(e))
            else:
                res.update(action="error", error=str(e))
    return results


# --- auto-fix promotion --------------------------------------------------------------

def promotions_this_week(run, now):
    hits = gh_json(run, "issue", "list", "--state", "all", "--search", f'"{PROMOTED}" in:comments',
                   "--json", "number,comments", "--limit", "100") or []
    return sum(1 for issue in hits for c in issue["comments"]
               if PROMOTED in c.get("body", "") and _parse(c["createdAt"]) >= now - timedelta(days=7))


def autofix_eligible(f, config):
    cfg = config["autoFix"]
    return (f["severity"] in cfg["severities"] and f["confidence"] == "high" and bool(f.get("repro"))
            and isinstance(f.get("tier"), int) and f["tier"] <= cfg["maxTier"])


def promote(run, confirmed, filed, config, *, source, roles, now):
    """Move eligible filed issues to ready-for-agent, within the weekly PR cap.

    Returns (promoted issue numbers, skipped [{id, reason}]).
    """
    by_id = {f["id"]: f for f in confirmed}
    triage = roles.get("needs-triage", "needs-triage")
    agent_labels = {roles.get(r, r) for r in AGENT_ROLES}
    budget = config["maxPrsPerWeek"] - promotions_this_week(run, now)
    promoted, skipped = [], []
    for res in filed:
        f = by_id.get(res["id"])
        if not res.get("issue") or f is None:
            continue
        if not autofix_eligible(f, config):
            skipped.append({"id": res["id"], "reason": "not eligible"})
            continue
        if triage not in res.get("labels", []) or agent_labels & set(res.get("labels", [])):
            skipped.append({"id": res["id"], "reason": "already triaged or claimed"})
            continue
        if budget <= 0:
            skipped.append({"id": res["id"], "reason": "weekly PR cap reached"})
            continue
        n = str(res["issue"])
        gh(run, "issue", "edit", n, "--remove-label", triage, "--add-label", roles.get("ready-for-agent", "ready-for-agent"))
        gh(run, "issue", "comment", n, "--body",
           NOTICE.format(source=source) + f"Queued for auto-fix: confirmed {f['severity']}, tier {f['tier']}, "
           f"with a failing reproduction test.\n\n`{PROMOTED}`")
        promoted.append(res["issue"])
        budget -= 1
    return promoted, skipped
